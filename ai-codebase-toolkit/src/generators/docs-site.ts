import { GeneratedFile, ScanResult } from '../core/types';

/**
 * Generates a complete VitePress documentation site, runnable locally with:
 *   npm install --prefix docs && npm run docs:dev
 *
 * Pages cover: overview, getting started, architecture, modules, API reference,
 * decisions (ADR index), specs (SDD index), contributing, glossary.
 *
 * The skeleton is filled with TODO(ai) markers so the user's AI can flesh out
 * each page from the actual codebase.
 */
