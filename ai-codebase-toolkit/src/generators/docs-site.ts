function page(title: string, body: string): string {
  return `# ${title}\n\n${body}\n`;
}

function inferProjectName(scan: ScanResult): string {
  const last = scan.rootPath.split(/[\\/]/).filter(Boolean).pop() ?? 'project';
  return last;
}
